"""Interactive dashboard for GeoPulse GPS movement analytics."""
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "processed"

st.set_page_config(
    page_title="GeoPulse | Movement Analytics",
    page_icon="🌍",
    layout="wide",
)

st.title("GeoPulse")
st.subheader("GPS-Based Movement Analytics System")
st.caption(
    "Exploring synthetic GPS movement data around Bhopal, India. "
    "Results describe the generated dataset, not real people or devices."
)

@st.cache_data
def load_csv(filename):
    path = DATA / filename
    if not path.exists():
        return None
    return pd.read_csv(path)

movement = load_csv("movement_metrics.csv")
patterns = load_csv("movement_patterns.csv")
devices = load_csv("device_clusters.csv")
profiles = load_csv("cluster_profiles.csv")
evaluation = load_csv("clustering_evaluation.csv")

required = {
    "Movement metrics": movement,
    "Movement patterns": patterns,
    "Device clusters": devices,
    "Cluster profiles": profiles,
    "Clustering evaluation": evaluation,
}

missing = [name for name, frame in required.items() if frame is None]

if missing:
    st.error("Missing processed datasets: " + ", ".join(missing))
    st.info("Run the analytics pipeline first: python run_pipeline.py")
    st.stop()

if devices.empty:
    st.warning("The device clustering dataset is empty.")
    st.stop()

total_devices = devices["DeviceID"].nunique()
total_observations = (
    devices["Total_Observations_movement"].sum()
    if "Total_Observations_movement" in devices.columns
    else len(movement)
)
total_distance = (
    devices["Total_Distance_KM"].sum()
    if "Total_Distance_KM" in devices.columns
    else float("nan")
)
cluster_count = (
    devices["Cluster"].nunique()
    if "Cluster" in devices.columns
    else 0
)

c1, c2, c3, c4 = st.columns(4)
c1.metric("Unique devices", f"{total_devices:,}")
c2.metric("GPS observations", f"{total_observations:,.0f}")
c3.metric(
    "Summed observed distance",
    f"{total_distance:,.1f} km" if pd.notna(total_distance) else "N/A",
)
c4.metric("Clusters", f"{cluster_count}")

overview, clusters, movement_tab, data_tab = st.tabs(
    ["Overview", "Clusters", "Movement", "Data quality"]
)

with overview:
    st.header("Movement overview")

    if "Cluster" in devices.columns:
        counts = devices["Cluster"].value_counts().sort_index()
        st.write("Devices per cluster")
        st.bar_chart(counts)

    left, right = st.columns(2)

    with left:
        if "Average_Distance_KM" in profiles.columns:
            chart_data = profiles.set_index("Cluster")[
                ["Average_Distance_KM"]
            ]
            st.write("Average distance by cluster")
            st.bar_chart(chart_data)

    with right:
        if "Average_Speed_KMH" in profiles.columns:
            chart_data = profiles.set_index("Cluster")[
                ["Average_Speed_KMH"]
            ]
            st.write("Average speed by cluster")
            st.bar_chart(chart_data)

    st.info(
        "GPS observations may be separated by long time intervals. "
        "Summed distances represent observed straight-line segments, "
        "not necessarily actual road distance or complete journeys."
    )

with clusters:
    st.header("Cluster analysis")
    st.write("Cluster profiles generated by K-Means.")
    st.dataframe(profiles, use_container_width=True, hide_index=True)

    if evaluation is not None and not evaluation.empty:
        st.subheader("Silhouette evaluation")
        st.dataframe(
            evaluation,
            use_container_width=True,
            hide_index=True,
        )

        if {
            "Number_of_Clusters",
            "Silhouette_Score",
        }.issubset(evaluation.columns):
            chart = evaluation.set_index("Number_of_Clusters")[
                ["Silhouette_Score"]
            ]
            st.line_chart(chart)

    if "Cluster" in devices.columns:
        selected = st.selectbox(
            "Inspect a cluster",
            sorted(devices["Cluster"].dropna().unique().tolist()),
        )
        subset = devices[devices["Cluster"] == selected]
        st.write(f"Devices in selected cluster: {len(subset):,}")
        st.dataframe(subset, use_container_width=True, hide_index=True)

with movement_tab:
    st.header("Movement metrics")

    if "Speed_KMH" in movement.columns:
        speeds = pd.to_numeric(
            movement["Speed_KMH"], errors="coerce"
        ).dropna()
        speeds = speeds[speeds >= 0]

        if not speeds.empty:
            upper = speeds.quantile(0.99)
            st.caption(
                f"Speed chart is capped at the 99th percentile "
                f"({upper:.2f} km/h) for readability. "
                "The underlying CSV retains its original values."
            )
            st.line_chart(
                speeds[speeds <= upper].reset_index(drop=True)
            )

    if {
        "Average_Speed_KMH",
        "Total_Distance_KM",
    }.issubset(devices.columns):
        plot_data = devices[
            ["Total_Distance_KM", "Average_Speed_KMH"]
        ].apply(pd.to_numeric, errors="coerce").dropna()

        st.subheader("Device distance versus average speed")
        if not plot_data.empty:
            fig, ax = plt.subplots()
            ax.scatter(
                plot_data["Total_Distance_KM"],
                plot_data["Average_Speed_KMH"],
                alpha=0.55,
            )
            ax.set_xlabel("Observed distance (km)")
            ax.set_ylabel("Average observed speed (km/h)")
            ax.set_title("Distance vs. average speed")
            ax.grid(True, alpha=0.25)
            st.pyplot(fig)
            plt.close(fig)

    st.subheader("Movement records")
    st.dataframe(
        movement.head(500),
        use_container_width=True,
        hide_index=True,
    )

with data_tab:
    st.header("Dataset inspection")

    for name, frame in required.items():
        with st.expander(f"{name} — {len(frame):,} rows"):
            st.write("Columns:", ", ".join(frame.columns.astype(str)))
            st.dataframe(
                frame.head(100),
                use_container_width=True,
                hide_index=True,
            )

    st.subheader("Missing values")
    quality = pd.DataFrame(
        {
            name: frame.isna().sum()
            for name, frame in required.items()
        }
    )
    st.dataframe(quality, use_container_width=True)

    st.caption(
        "Missing values in derived speed fields can be expected when "
        "a device has insufficient consecutive observations."
    )

st.divider()
st.caption(
    "GeoPulse | GPL-3.0 | Synthetic-data analytics demonstration"
)
